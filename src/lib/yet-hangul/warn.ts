/**
 * 옛한글 경고 문구 — 기출·프린트·이어 읽기가 같은 말을 쓰도록 한 곳에 둔다.
 *
 * 왜 경고를 내는가: 옛 글자는 선생님도 눈으로 한 번 더 봐야 한다. 모델이 비슷한 다른 자모로
 * 읽어도 화면에서는 그럴듯해 보이기 때문이다. **쪽 단위로** 알리는 것이 규칙이다 —
 * 중세국어 시험지는 거의 모든 항목에 옛한글이 있어 항목마다 붙이면 경고 상한을 먹어
 * 진짜 경고(빠진 쪽·못 읽은 선지)를 밀어낸다.
 */

/**
 * 그 쪽에 옛한글이 있다는 알림.
 * @param page - 원본 쪽 번호
 * @returns 경고 문구
 */
export function yetHangulPageWarning(page: number): string {
  return `${page}쪽에 옛한글이 있어요. 자모가 맞는지 원본과 대조해 주세요.`;
}

/** 이어 읽기는 쪽이 하나뿐이라 쪽 번호 없이 말한다 */
export const YET_HANGUL_CONTINUATION_WARNING =
  '이어 붙인 글에 옛한글이 있어요. 자모가 맞는지 원본과 대조해 주세요.';

/**
 * 대체 표기를 자모로 못 바꾼 자리가 남았다는 알림 — 이쪽은 **항목 단위**다(진짜 실패라 드물다).
 */
export const UNCONVERTED_NOTATION_WARNING =
  '옛한글 표기 ⟦ ⟧ 를 자모로 못 바꾼 곳이 있어요. 검수에서 고쳐 주세요.';
