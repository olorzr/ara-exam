/**
 * 문답 시험지의 정책값.
 *
 * 두 턴이 서로 다른 성질이라 값도 따로 둔다 — **나누기**는 원문을 옮겨 적는 일(길고 정확해야
 * 한다)이고, **모범답안**은 짧은 글을 여러 개 짓는 일(참고자료까지 함께 읽는다)이다.
 */

/** 한 프린트에서 나눌 수 있는 최대 문항 수. 프린트 세 쪽이면 이 정도가 한계다 */
export const PRINT_QA_MAX_ITEMS = 80;

/** 인쇄된 번호의 길이 상한 — '3-1'·'(2)' 정도라 짧다 */
export const PRINT_QA_LABEL_MAX = 20;

/** 물음 한 개의 길이 상한 (글자). 보기까지 딸린 물음이 있어 넉넉히 둔다 */
export const PRINT_QA_QUESTION_MAX = 1_000;

/** 답 한 개의 길이 상한 (글자). 서술형이라 O,X·단답형(40자)보다 훨씬 길다 */
export const PRINT_QA_ANSWER_MAX = 600;

/**
 * 답을 그 문항의 것으로 인정할 **거리 상한** (글자).
 *
 * ⚠️ '다음 물음까지' 만으로는 모자라다(코덱스 6R). 가운데 문항을 모델이 **못 옮기면** 그
 *    문항의 자리를 우리가 모르므로 구역이 그 너머까지 벌어지고, 앞 문항이 **뒤 문항의 답**을
 *    제 답으로 삼는다(손글씨 판정까지 함께 틀어진다). 답은 물음 바로 뒤에 붙어 있으므로
 *    거리로도 함께 묶는다 — 넘어서 찾은 답은 버리지 않되 '다른 곳에서 찾았다' 로 알린다.
 *
 * ⚠️ 이 값은 **물음 끝에서 답이 시작하기까지의 거리**다(코덱스 7R). 답 길이를 함께 더하지 않으면
 *    600자짜리 긴 답이 바로 옆에 있어도 구역 밖으로 밀려나, 문서 전체를 뒤져 **같은 글자의 다른
 *    자리**를 집어 온다(손글씨 판정까지 틀어진다).
 */
export const PRINT_QA_ANSWER_REGION_MAX = 600;

/** 근거 구절의 길이 상한. 문장 하나면 충분하다(`PASSAGE_QUIZ_EVIDENCE_MAX` 와 같은 값) */
export const PRINT_QA_EVIDENCE_MAX = 200;

/**
 * 물음 앞 지문·지시문의 길이 상한.
 *
 * 넉넉히 잡는다 — 이 글은 **모델에게 보내지 않고** 저장·인쇄만 하므로 프롬프트 예산과 무관하고,
 * 학교 프린트의 지문은 시 한 편·소설 한 대목이라 수천 자가 예사다(코덱스 5R: 2,000자로 잡았더니
 * 2,100자 지문의 **앞부분이 조용히 잘렸다**). 넘으면 잘랐다는 것을 사람에게 알린다.
 */
export const PRINT_QA_LEAD_MAX = 20_000;

/** 본문 길이 상한 — 넘으면 보내지 않고 먼저 사람에게 알린다(`print-words` 와 같은 값) */
export const PRINT_QA_TEXT_LIMIT = 40_000;

/** 본문 + 참고자료 평문의 **합** 상한. 넘으면 참고자료를 빼라고 알린다 */
export const PRINT_QA_BUNDLE_LIMIT = 100_000;

/**
 * 나누기 턴의 워치독.
 *
 * 이미지가 없어 왕복은 한 번이지만 **출력이 길다** — 문항 수십 개의 물음과 답을 원문 그대로
 * 옮겨 적으므로 기본 120초로는 아깝게 끊긴다.
 */
export const PRINT_QA_SPLIT_TIMEOUT_MS = 300_000;

/** 모범답안 턴의 워치독 — 참고자료를 함께 읽으므로 `PASSAGE_QUIZ_TIMEOUT_MS` 와 같은 값 */
export const PRINT_QA_ANSWER_TIMEOUT_MS = 180_000;

/** 한 번에 모범답안을 만들 수 있는 최대 문항 수 */
export const PRINT_QA_ANSWER_MAX_TARGETS = 40;

/** 영수증에 남길 경고 수 상한 — 안 걸면 qa_meta 가 끝없이 커진다 */
export const PRINT_QA_MAX_WARNINGS = 20;

/**
 * 목록에서 '문답 프린트로 보인다' 고 볼 최소 '답:' 수.
 *
 * ⚠️ **힌트에만 쓴다.** 이 판정으로 기능을 막거나 자동으로 돌리지 않는다 — 프린트 모양은
 *    제각각이라 '답:' 없이 괄호로만 답을 적은 것도 있고, 시 한 편만 실린 프린트에도
 *    '답:' 이 두 번 나올 수 있다.
 */
export const PRINT_QA_HINT_MIN_ANSWERS = 2;
