/**
 * 개념 목록 끝에 `혼합` 을 단다(개념이 셋 이상일 때만).
 *
 * 마스터 원본에 손으로 적지 않고 규칙으로 붙이는 까닭: 가지를 새로 더할 때 빠뜨리면 그 가지만
 * 혼합 칸이 없어 종합 문항이 다시 잎 여럿으로 흩어진다. **맨 뒤**인 것은 '더한 것은 뒤에' 규약이다.
 * @param leaves - 마스터의 개념 이름들
 * @returns 화면·저장에 쓰는 잎 이름들
 */
function withMixedLeaf(leaves: string[]): string[] {
  return leaves.length >= GRAMMAR_MIXED_MIN_CONCEPTS ? [...leaves, GRAMMAR_MIXED_LEAF] : leaves;
}

/**
 * 마스터 원본을 트리로 편다.
 *
 * id 는 합성값이다 — 실제 UUID 가 없는 것은 카테고리 관리의 마스터 전개 노드와 같다.
 * @returns 선언 순서를 지킨 트리
 */
function buildGrammarTree(source: GrammarSource): AreaTreeNode[] {
  const leafNodes = (leaves: string[], prefix: string): AreaTreeNode[] => withMixedLeaf(leaves)
    .map((leaf, k) => ({ id: `${prefix}-${k}`, name: leaf, children: [] }));
  return Object.entries(source).map(([major, body], i) => ({
    id: `g${i}`,
    name: major,
    children: Array.isArray(body)
      ? leafNodes(body, `g${i}`)
      : Object.entries(body).map(([mid, leaves], j) => ({
        id: `g${i}-${j}`,
        name: mid,
        children: leafNodes(leaves, `g${i}-${j}`),
      })),
  }));
}

