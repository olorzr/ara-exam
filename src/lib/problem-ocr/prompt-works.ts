/** 후보를 몇 개까지 프롬프트에 실을 것인가 — 길어지면 모델이 목록에서 고르려 든다 */
export const WORK_HINT_MAX = 20;

/**
 * 이번 묶음 안내에 붙일 작품 후보 한 줄.
 * @param hints - 작품 후보 (없으면 빈 배열)
 * @returns 안내 한 줄
 */
export function workHintLine(hints: readonly string[]): string {
  return hints.length > 0
    ? '- 작품후보가 주어졌다. 같은 작품이면 **후보의 표기를 그대로** 쓴다.'
    : '- 작품후보가 없다. 인쇄된 이름과 본문으로 판단한다.';
}

/**
 * 데이터 블록에 실을 작품 후보.
 *
 * ⚠️ 상한을 넘기면 **앞에서 자른다** — 후보는 가까운 순으로 오므로 뒤엣것이 덜 중요하다.
 * @param hints - 작품 후보
 * @returns 실을 목록. 없으면 null (빈 배열을 실으면 "후보가 있는데 비었다"로 읽힌다)
 */
export function workHintData(hints: readonly string[]): string[] | null {
  return hints.length > 0 ? [...hints].slice(0, WORK_HINT_MAX) : null;
}
