/** AI 추천 빈칸의 정책값 */

/**
 * 설명 100자에 몇 개를 뚫는가 — **선생님이 손으로 마킹한 개념지 121장의 실측값**이다
 * (2026-09-15 분석: 마킹 8,100개 / 본문 1,000자당 중앙값 52개 = 100자당 5.2개).
 *
 * ⚠️ 이 값을 '10개 안팎' 같은 장당 개수로 되돌리지 말 것. 예전 프롬프트가 그랬고,
 *    그 결과 AI 가 뚫은 프린트는 1,000자당 9~14개로 **선생님 기준의 1/5** 이었다.
 *    양은 본문 길이에 비례하지, 시험지 한 장에 정해져 있지 않다.
 */
export const CONCEPT_PICK_DENSITY_PER_100 = 5;

/**
 * **묶음 하나**에서 받을 수 있는 최대 개수.
 * 스키마 `maxItems`·프롬프트의 상한 문구·파서의 자름이 **전부 이 값 하나**를 본다 —
 * 셋이 갈라지면 모델이 스키마를 어겨 출력이 통째로 실패한다.
 *
 * 묶음 크기(`CONCEPT_PICK_CHUNK_CHARS`)와 밀도(`CONCEPT_PICK_DENSITY_PER_100`)를 곱하면
 * 묶음당 기대치가 50개다 — 상한은 그보다 한 뼘 위여야 빽빽한 표에서 잘리지 않는다.
 */
export const CONCEPT_PICK_MAX_COUNT = 60;

/**
 * 본문을 몇 글자씩 나눠 물을 것인가.
 *
 * 한 번에 다 물을 수 없다: 개념지 한 장(본문 중앙값 1,235자)의 마킹이 60개라 긴 시험지는
 * 수백 개가 되는데, 그만큼을 한 응답에 담으면 스키마 상한에 잘리고 출력 토큰도 그만큼 는다.
 * 대신 묶음마다 한 번씩 묻고 **받는 즉시 마킹한다** — 중간에 멈춰도 거기까지는 남는다.
 */
export const CONCEPT_PICK_CHUNK_CHARS = 1_000;

/** 용어 하나의 길이 상한 (글자) */
export const CONCEPT_PICK_TEXT_MAX = 40;

/**
 * 용어의 최소 길이.
 *
 * 한 글자를 허용하면 `findMarkTarget` 의 `indexOf` 가 **더 긴 낱말 안쪽**을 잡는다
 * ('시' 가 '자유시' 안에서 걸린다). 두 글자여도 완전히 막히지는 않지만 크게 줄어든다.
 *
 * ⚠️ 선생님은 실제로 한 글자도 뚫는다(뜻·꿈·말·삶·힘 — 실측 5.6%). **알고도 막는 것**이다:
 *    엉뚱한 낱말 속에 구멍이 뚫리는 쪽이 한 글자 몇 개를 놓치는 것보다 나쁘다.
 */
export const CONCEPT_PICK_TEXT_MIN = 2;

/**
 * 자리 힌트(`context`)의 길이 상한.
 *
 * 같은 낱말이 작품 원문과 풀이 표에 다 있을 때 **어느 쪽에 빈칸을 뚫을지** 정하는 재료다.
 * 길게 받을 이유가 없다 — 표 한 칸이나 문장 하나면 자리가 정해진다.
 */
export const CONCEPT_PICK_CONTEXT_MAX = 60;

/** 본문 길이 상한 — 넘으면 보내지 않고 사람에게 알린다 */
export const CONCEPT_PICK_TEXT_LIMIT = 40_000;

/** 묶음 하나는 짧아 기본 워치독으로 충분하다 */
export const CONCEPT_PICK_TIMEOUT_MS = 120_000;
