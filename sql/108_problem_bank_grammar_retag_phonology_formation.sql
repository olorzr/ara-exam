  SELECT count(*) INTO v FROM exam.problems p
   WHERE EXISTS (SELECT 1 FROM unnest(p.grammar_paths) g WHERE g LIKE '남북한 언어 > %')
     AND EXISTS (SELECT 1 FROM unnest(p.grammar_paths) g WHERE g LIKE '음운 > %');
