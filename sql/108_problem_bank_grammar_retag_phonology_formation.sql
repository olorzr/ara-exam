  FOR r IN SELECT g, count(*) n FROM exam.problems, unnest(grammar_paths) g
            WHERE g LIKE '음운 > %' OR g LIKE '단어 > 단어의 형성 > %' OR g LIKE '어문 규정 > %' OR g LIKE '남북한 언어 > %'
            GROUP BY 1 ORDER BY 1 LOOP
    RAISE NOTICE '  %건 : %', r.n, r.g;
  END LOOP;
