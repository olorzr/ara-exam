   WHERE area_path && ARRAY['언어'] AND cardinality(grammar_paths) = 0;
  RAISE NOTICE '검증: 미태깅 %건 (기대 0 — 기출을 새로 올렸으면 그만큼 는다)', v;

  IF v_changed > 0 THEN
    -- 이번에 고쳤다 = 복구본이거나 첫 적용이다. 선언한 최종 상태와 한 건이라도 어긋나면 멈춘다.
    SELECT count(*) INTO v_bad
      FROM damhwa_ids d JOIN exam.problems p ON p.id = d.id
     WHERE p.area_path <> ARRAY['화법과 언어','언어'] OR p.grammar_paths <> ARRAY[d.leaf];
    IF v_bad > 0 THEN RAISE EXCEPTION '검증 실패: 1단계 결과가 어긋난 문항 %건', v_bad; END IF;

    -- 기대값 = 2단계 목록에 3단계 치환을 먹인 것
    SELECT count(*) INTO v_bad
      FROM backfill_ids b
      JOIN exam.problems p ON p.id = b.id
      LEFT JOIN nk_ids n ON n.id = b.id
     WHERE p.grammar_paths <> CASE
             WHEN n.id IS NULL THEN b.paths
             ELSE array_replace(array_replace(b.paths, c_via, n.leaf), c_mid, n.leaf)
           END;
    IF v_bad > 0 THEN RAISE EXCEPTION '검증 실패: 2·3단계 결과가 어긋난 문항 %건', v_bad; END IF;

    SELECT count(*) INTO v_bad FROM exam.problems
     WHERE area_path && ARRAY['언어'] AND cardinality(grammar_paths) = 0;
    IF v_bad > 0 THEN RAISE EXCEPTION '검증 실패: 미태깅 문법 문항이 %건 남았다', v_bad; END IF;

    RAISE NOTICE '검증: 선언한 최종 상태와 모두 일치 (바꾼 행 %건)', v_changed;
  ELSE
    RAISE NOTICE '검증: 바꾼 행 0건 — 이미 적용돼 있다. 아래는 현재 값(강제하지 않음)';
  END IF;

END
$backfill$;

