  FOR r IN SELECT * FROM _plan LOOP
    UPDATE exam.passages p
       SET works = COALESCE((
             SELECT jsonb_agg(
                      CASE WHEN e->>'title' = r.from_title AND r.to_author IS NOT NULL
                             THEN jsonb_set(jsonb_set(e, '{title}', to_jsonb(r.to_title)),
                                            '{author}', to_jsonb(r.to_author))
                           WHEN e->>'title' = r.from_title
                             THEN jsonb_set(e, '{title}', to_jsonb(r.to_title))
                           ELSE e END
                      ORDER BY ord)
               FROM jsonb_array_elements(p.works) WITH ORDINALITY AS a(e, ord)
              WHERE NOT (e->>'title' = r.from_title AND r.to_title IS NULL)),
             '[]'::jsonb)
     WHERE p.id = r.passage_id
       AND exam.works_titles(p.works) @> ARRAY[r.from_title];
    GET DIAGNOSTICS v_n = ROW_COUNT;
    IF v_n = 1 THEN v_done := v_done + 1; ELSE v_skip := v_skip + 1; END IF;
