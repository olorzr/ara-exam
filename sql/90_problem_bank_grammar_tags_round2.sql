DO $tags$
DECLARE
  v_total INT;
  v_done  INT;
  v_bad   INT;
BEGIN
  IF to_regclass('exam.problems') IS NULL THEN
    RAISE EXCEPTION 'exam.problems 가 없습니다 (현재 DB: %).', current_database();
  END IF;
  SELECT count(*) INTO v_total FROM _tags;

  UPDATE exam.problems p SET grammar_paths = t.paths
    FROM _tags t WHERE p.id = t.id AND cardinality(p.grammar_paths) = 0;
  GET DIAGNOSTICS v_done = ROW_COUNT;
  RAISE NOTICE '태그 단 문항 % / 이미 값이 있어 건너뜀 % (목록 %)', v_done, v_total - v_done, v_total;

  -- 검증 — 태그가 빈 채 남은 것이 없는가
  SELECT count(*) INTO v_bad FROM _tags t JOIN exam.problems p ON p.id = t.id WHERE cardinality(p.grammar_paths) = 0;
  IF v_bad > 0 THEN RAISE EXCEPTION '태그가 빈 문항 %건이 남았습니다.', v_bad; END IF;
END
