--
-- 왜: 빠진 기출 목록을 뽑을 때마다 원래 없던 시험(중3 2학기 중간, 기말만 보는 학교의 중간 등)이
--     '빠진 것'으로 다시 올라와 데스크가 같은 것을 또 찾았다. 원장님: "내가 다시는 이거를 찾지 않도록".
-- 무엇: exam.naesin_exams_not_held — 학교·학년도·학년·학기·시험 한 칸이 '시험 없음'이라는 기록.
--       빠진 기출 목록 도구(~/.claude/tools/exam-specs/naesin-gaps/gaps.cjs)가 이 표의 칸을 목록에서 뺀다.
-- 데이터: 데스크가 X 로 표시한 130칸(2026-11-19) 중 올해(2026) 두 칸을 뺀 128칸 — 올해 칸은 '시험 없음'으로 두지 않는다(sql/112). 증거와 어긋나는 13칸은 넣지 않았다 —
--   2026 1학기 광희·동마 중2·중3: 학생 성적(naesin_results)이 들어와 있어 실제로 본 시험(마장도 같은 표시라 함께 보류),
--   2023 마장 중3 1학기 기말: 받은 원안지 쪽 머리가 '2023학년도 1학기 3학년 기말고사'.
-- 안전장치: 넣을 칸에 이미 적재된 기출(problem_sources)이 있으면 통째로 멈춘다.
-- 멱등: IF NOT EXISTS · ON CONFLICT DO NOTHING · DROP POLICY IF EXISTS.

BEGIN;

CREATE TABLE IF NOT EXISTS exam.naesin_exams_not_held (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_name  text NOT NULL CHECK (school_name <> ''),           -- problem_sources.school_name 과 같은 정식 이름
  year         text NOT NULL CHECK (year ~ '^[0-9]{4}$'),         -- problem_sources.year 와 같은 text 학년도
  grade        text NOT NULL CHECK (grade ~ '^(중|고)[1-3]$'),
  semester     text NOT NULL CHECK (semester IN ('1학기', '2학기')),
  exam_type    text NOT NULL CHECK (exam_type IN ('중간', '기말')),
  reason       text NOT NULL DEFAULT '시험 없음',
  confirmed_by text NOT NULL DEFAULT '',                          -- 누가 확인했나(예: 데스크)
  confirmed_on date NOT NULL DEFAULT current_date,
  created_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (school_name, year, grade, semester, exam_type)
);

COMMENT ON TABLE exam.naesin_exams_not_held IS
  '학교가 그 내신 시험을 아예 안 본 칸(시험 없음). 빠진 기출 목록에서 뺀다. 나중에 그 칸 기출이 들어오면 이 행을 지운다. sql/111';

